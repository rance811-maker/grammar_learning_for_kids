// 自定义课程的语法点是 AI 现取的名字，表里不一定有。至少把下划线拆开、
// 首字母大写，别让家长盯着 mixed_tense_sequences 这种字符串发呆。
function humanize(skill) {
  return String(skill)
    .replace(/_/g, ' ')
    .replace(/\b[a-z]/g, (c) => c.toUpperCase());
}

/** 展示用名字：查得到中文就用中文，查不到就把英文排版得像人话。 */
export function skillName(skill) {
  if (!skill) return '';
  return SUB_SKILL_NAMES[skill] || humanize(skill);
}

/** 英文原名（已排版），用于在中文旁边作小字备注。 */
export function skillEnglish(skill) {
  return humanize(skill);
}

/** 中文和英文是不是两个不同的说法——相同就没必要并排显示两遍。 */
export function hasChineseName(skill) {
  return !!SUB_SKILL_NAMES[skill];
}
